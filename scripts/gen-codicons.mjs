// Writes src/webview/codicons.ts: the Codicons (VS Code's own icon set, @vscode/codicons,
// CC-BY-4.0) that the webviews use, as inline SVG paths. Inline SVG rather than the codicon
// font: constraint 2 rules out a bundled webfont, and an inline path still takes the theme's
// color through currentColor. Add a name below and run `node scripts/gen-codicons.mjs`.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const NAMES = [
  "archive", "arrow-swap", "case-sensitive", "check", "chevron-down", "chevron-right", "chevron-up", "clear-all", "close", "cloud-download", "dash", "diff", "diff-multiple", "discard",
  "collapse-all", "copy", "expand-all", "file", "files", "filter", "filter-filled", "folder", "git-branch", "git-commit",
  "git-compare", "git-merge", "history", "layout-sidebar-left", "layout-sidebar-right", "ellipsis", "pass", "person", "refresh", "regex",
  "repo", "repo-pull", "repo-push", "sort-precedence", "split-horizontal", "split-vertical", "star-empty", "star-full", "sync", "tag", "warning",
];

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const icons = path.join(root, "node_modules", "@vscode", "codicons", "src", "icons");
const version = JSON.parse(readFileSync(path.join(root, "node_modules", "@vscode", "codicons", "package.json"), "utf8")).version;

const entries = NAMES.map((name) => {
  const svg = readFileSync(path.join(icons, `${name}.svg`), "utf8");
  // Most codicons are 16×16; a few are drawn on 24×24. Each keeps its own viewBox and renders at 16 px.
  const viewBox = /viewBox="([^"]+)"/.exec(svg)?.[1];
  if (!viewBox) throw new Error(`${name}: no viewBox`);
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").trim();
  return `  "${name}": [${JSON.stringify(viewBox)}, ${JSON.stringify(inner)}],`;
});

writeFileSync(path.join(root, "src", "webview", "codicons.ts"), `// Generated by scripts/gen-codicons.mjs from @vscode/codicons ${version} (CC-BY-4.0, see ThirdPartyNotices.txt).
// Do not edit by hand: add the name to the script and run it again.

/** VS Code's own icons, so the webviews' buttons look like VS Code's toolbars. */
const PATHS = {
${entries.join("\n")}
} as const;

export type Codicon = keyof typeof PATHS;

/** A codicon as markup, for HTML built as a string (the host renders it; no document needed). */
export function codicon(name: Codicon, className = ""): string {
  const [viewBox, paths] = PATHS[name];
  return \`<svg class="codicon\${className ? \` \${className}\` : ""}" width="16" height="16" viewBox="\${viewBox}" fill="currentColor" aria-hidden="true" focusable="false">\${paths}</svg>\`;
}

const parsed = new Map<string, SVGElement>();

/** A codicon as an element (parsed once per name, then cloned). Webview only. */
export function codiconElement(name: Codicon, className = ""): SVGElement {
  const key = \`\${name} \${className}\`;
  let svg = parsed.get(key);
  if (!svg) {
    const t = document.createElement("template");
    t.innerHTML = codicon(name, className);
    svg = t.content.firstChild as SVGElement;
    parsed.set(key, svg);
  }
  return svg.cloneNode(true) as SVGElement;
}
`);
console.log(`ok - ${NAMES.length} codicons from @vscode/codicons ${version}`);
